def sleep_interval() -> None:
    time.sleep(REQUEST_INTERVAL)


def request_json(
    session: requests.Session,
    method: str,
    url: str,
    token: str | None = None,
    json_body: dict | None = None,
) -> dict:
    headers = {}
    if token:
        headers["Authorization"] = f"Bearer {token}"

    last_error: Exception | None = None
    for attempt in range(1, MAX_RETRIES + 2):
        try:
            sleep_interval()
            response = session.request(
                method=method,
                url=url,
                headers=headers if headers else None,
                json=json_body,
                timeout=REQUEST_TIMEOUT,
            )
            response.raise_for_status()
            return response.json()
        except Exception as exc:  # pylint: disable=broad-except
            last_error = exc
            if attempt <= MAX_RETRIES:
                print(f"[retry {attempt}/{MAX_RETRIES}] {method} {url} failed: {exc}")
                continue
            break
    raise RuntimeError(f"Request failed after retries: {method} {url} -> {last_error}") from last_error


def login(session: requests.Session) -> Tuple[str, str]:
    for base_url in BASE_URLS:
        login_url = f"{base_url}/user/auth/login"
        try:
            payload = request_json(
                session=session,
                method="POST",
                url=login_url,
                json_body={"username": USERNAME, "password": PASSWORD},
            )
            if payload.get("code") == 200 and payload.get("data", {}).get("token"):
                token = payload["data"]["token"]
                print(f"Login success: {base_url}")
                return base_url, token
            print(f"Login response not successful at {base_url}: {payload}")
        except Exception as exc:  # pylint: disable=broad-except
            print(f"Login failed at {base_url}: {exc}")
    raise RuntimeError("Unable to login on all base URLs")


def create_kb(session: requests.Session, base_url: str, token: str, department: str) -> int:
    payload = request_json(
        session=session,
        method="POST",
        url=f"{base_url}/knowledge/kb",
        token=token,
        json_body={
            "name": f"{department}知识库",
            "description": f"{department}常见疾病与健康管理知识库，含20条结构化医学常识条目。",
        },
    )
    if payload.get("code") != 200:
        raise RuntimeError(f"Create KB failed for {department}: {payload}")
    kb_id = payload.get("data")
    print(f"[{department}] kb_id={kb_id}")
    return kb_id


def add_chunk(
    session: requests.Session,
    base_url: str,
    token: str,
    kb_id: int,
    department: str,
    index: int,
    topic: str,
    counters: Counters,
) -> None:
    content = build_content(department, topic)
    print(f"[{department}] chunk {index}/20: {topic}")
    payload = request_json(
        session=session,
        method="POST",
        url=f"{base_url}/knowledge/kb/{kb_id}/chunk",
        token=token,
        json_body={"title": topic, "content": content},
    )
    code = payload.get("code")
    if code == 200:
        counters.success += 1
        return
    if code == 5003:
        counters.skipped += 1
        print(f"[WARN] [{department}] {topic}: embedding unavailable (code=5003), skipped")
        return
    raise RuntimeError(f"Add chunk failed for [{department}] {topic}: {payload}")


def validate_dataset() -> None:
    missing = []
    for topics in DEPARTMENT_TOPICS.values():
        for topic in topics:
            if topic not in TOPIC_FACTS:
                missing.append(topic)
    if missing:
        raise ValueError(f"Missing TOPIC_FACTS for topics: {missing}")


def main() -> int:
    validate_dataset()
    session = requests.Session()
    counters = Counters()
    total = sum(len(items) for items in DEPARTMENT_TOPICS.values())
    print(f"Start seeding: 10 knowledge bases, {total} chunks")

    base_url, token = login(session)
    for department, topics in DEPARTMENT_TOPICS.items():
        if len(topics) != 20:
            raise ValueError(f"{department} topic count != 20")
        kb_id = create_kb(session, base_url, token, department)
        for idx, topic in enumerate(topics, start=1):
            add_chunk(session, base_url, token, kb_id, department, idx, topic, counters)

    print("Seeding completed.")
    print(f"Summary: success={counters.success}, skipped={counters.skipped}, total={total}")
    return 0


